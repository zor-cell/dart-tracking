/**
 * Writes src/environments/license.ts (gitignored) with the PrimeUI license key:
 * PRIMEUI_LICENSE_KEY from the environment, else from the repository's root .env.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const name = 'PRIMEUI_LICENSE_KEY';

function fromDotEnv() {
  const file = join(root, '..', '.env');
  if (!existsSync(file)) return undefined;
  const line = readFileSync(file, 'utf8')
    .split(/\r?\n/)
    .find((entry) => entry.startsWith(`${name}=`));
  return line?.slice(name.length + 1).trim().replace(/^(['"])(.*)\1$/, '$2');
}

const key = process.env[name]?.trim() || fromDotEnv() || '';
if (!key) console.warn(`${name} is not set; PrimeNG will show a license notice`);

const target = join(root, 'src', 'environments', 'license.ts');
writeFileSync(
  target,
  `// Generated by scripts/generate-license.mjs. Do not edit.\nexport const PRIMEUI_LICENSE = ${JSON.stringify(key)};\n`,
);
