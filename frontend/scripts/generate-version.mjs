/**
 * Writes src/environments/version.ts before a build or a dev server start:
 * major.minor from package.json plus the build counter CI passes as BUILD_NUMBER.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const { version } = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const [major, minor] = version.split('.');
const build = process.env.BUILD_NUMBER?.trim() || 'dev';

const target = join(root, 'src', 'environments', 'version.ts');
const contents = `// Generated by scripts/generate-version.mjs. Do not edit.
export const APP_VERSION = '${major}.${minor}.${build}';
`;

writeFileSync(target, contents);
console.log(`version ${major}.${minor}.${build}`);
