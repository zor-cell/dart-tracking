/**
 * Writes src/environments/version.ts before a build or a dev server start:
 * package.json's version plus the build counter CI passes as APP_BUILD.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const { version } = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const build = process.env.APP_BUILD?.trim() || 'dev';

const target = join(root, 'src', 'environments', 'version.ts');
const contents = `// Generated by scripts/generate-version.mjs. Do not edit.
export const APP_VERSION = '${version}.${build}';
`;

writeFileSync(target, contents);
console.log(`version ${version}.${build}`);
