"""Reads and writes player identities — the address book behind a game."""

from uuid import UUID

from sqlalchemy import select, update
from sqlalchemy.ext.asyncio import AsyncSession

from app.api.features.player.domain.player_identity import PlayerIdentity
from app.api.features.player.persistence.player import PlayerTable

_SEARCH_LIMIT = 20


def _is_uuid(value: str) -> bool:
    try:
        UUID(value)
    except ValueError:
        return False
    return True


def _to_domain(row: PlayerTable) -> PlayerIdentity:
    return PlayerIdentity(id=row.id, display_name=row.display_name, user_id=row.user_id)


class PlayerRepository:
    async def create(
        self,
        session: AsyncSession,
        display_name: str,
        *,
        owner_user_id: str | None,
        user_id: str | None = None,
    ) -> PlayerIdentity:
        row = PlayerTable(
            display_name=display_name, owner_user_id=owner_user_id, user_id=user_id
        )
        session.add(row)
        # The id is generated by the database, so it has to be read back.
        await session.flush()
        return _to_domain(row)

    async def search(
        self, session: AsyncSession, owner_user_id: str, prefix: str
    ) -> list[PlayerIdentity]:
        """Names starting with `prefix`, own entry first, then alphabetical. An
        empty prefix lists the whole address book."""
        statement = select(PlayerTable).where(PlayerTable.owner_user_id == owner_user_id)
        if prefix:
            statement = statement.where(PlayerTable.display_name.istartswith(prefix))

        rows = (
            await session.execute(
                statement.order_by(
                    PlayerTable.user_id.is_(None), PlayerTable.display_name
                ).limit(_SEARCH_LIMIT)
            )
        ).scalars().all()
        return [_to_domain(row) for row in rows]

    async def rename_self(
        self, session: AsyncSession, user_id: str, display_name: str
    ) -> None:
        """The account's own entry follows the account's display name — that row
        is what the player list shows for oneself."""
        await session.execute(
            update(PlayerTable)
            .where(
                PlayerTable.user_id == user_id,
                PlayerTable.owner_user_id == user_id,
            )
            .values(display_name=display_name)
        )

    async def owned(
        self, session: AsyncSession, ids: list[str], owner_user_id: str
    ) -> dict[str, PlayerIdentity]:
        """The requested identities that this account may use, keyed by id.

        Scoping the lookup to the owner is the whole point: without it any
        caller could hang a game on someone else's identity and move their
        statistics.
        """
        # Ids come straight from the request body; one that is not a uuid at all
        # would fail at bind time, so it is dropped and simply never matches.
        candidates = [id for id in ids if _is_uuid(id)]
        if not candidates:
            return {}

        rows = (
            await session.execute(
                select(PlayerTable).where(
                    PlayerTable.id.in_(candidates),
                    PlayerTable.owner_user_id == owner_user_id,
                )
            )
        ).scalars().all()
        return {row.id: _to_domain(row) for row in rows}


repository = PlayerRepository()
